export const CHULGEO_CATEGORIES = ['주거 철거', '상가·원상복구', '목공'];

export function chulgeoCategory(title = '') {
  const t = String(title);
  if (/목공|목수/.test(t)) return '목공';
  if (/원상복구|상가|식당|카페|PC방|편의점|병원|사무실|매장|헬스장|창고|간판|공장|술집|네일샵|집기|학원|점포|미용실|가게|노래방|모텔|숙박|치과|약국|폐업|폐점/.test(t)) return '상가·원상복구';
  if (/아파트|빌라|주택|원룸|싱크대|붙박이장|가벽|천장|베란다|도배|장판|샷시|화장실|욕실|마루|주방|타일|방 확장|부분 철거|인테리어 철거|올철거|전체 철거/.test(t)) return '주거 철거';
  return '';
}
