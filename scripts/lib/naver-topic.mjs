export function guessTopic({ title = '', mainKeyword = '', category = '', issue = '' } = {}) {
  const p = { text: `${title} ${mainKeyword}`, category, issue };
  for (const [test, topic] of RULES) if (test(p)) return topic;
  return '인테리어·DIY';
}

/** 프런트매터 topic 이 있으면 그것(목록에 없는 이름이면 null 로 알린다), 없으면 규칙으로 */
export function topicFor(post) {
  const t = (post.topic || '').trim();
  if (t) return NAVER_TOPICS.includes(t) ? t : null;
  return guessTopic(post);
}
