/**
 * 네이버 블로그 글 '주제' (발행 패널의 주제 칸) 고르기.
 *
 * 2026-10-26 아침 확인: 발행 화면 캡처에서 살림 글(커튼 세탁·구스 이불 세탁)의 주제가 모두 '비즈니스·경제' 였다 —
 * 발행 스크립트가 주제를 고르지 않아 카테고리 기본값이 들어갔다. 홈판은 읽는 사람의 관심 주제로 글을 보여 주므로
 * 글 내용과 맞는 주제를 고른다 (사용자 — "너가 더 괜찮다고 판단되는 방향으로").
 *
 * 원고 프런트매터 `topic:` 이 있으면 그 이름, 없으면 제목·메인 키워드·카테고리로 아래 규칙에서 고른다.
 * 이름은 네이버 주제 목록의 글자 그대로 (가운뎃점 ·).
 */

export const NAVER_TOPICS = [
  // 생활·노하우·쇼핑
  '일상·생각', '육아·결혼', '반려동물', '좋은글·이미지', '패션·미용', '인테리어·DIY', '요리·레시피', '상품리뷰', '원예·재배',
  // 취미·여가·여행
  '국내여행', '세계여행', '맛집', '취미',
  // 지식·동향
  '건강·의학', '비즈니스·경제', '교육·학문',
];

const RULES = [
  // 생활보장 = 의료비·돌봄·건강 제도 (2026-10-26 원고부터 건강 글 포함)
  [(p) => p.category === '생활보장', '건강·의학'],
  [(p) => /화분|식물|다육|몬스테라|원예|분갈이|텃밭/.test(p.text), '원예·재배'],
  [(p) => /축제|명소|단풍|억새|꽃구경|나들이|캠핑|등산|여행|가볼|주차/.test(p.text), '국내여행'],
  // 옷·침구·집 살림이 먼저 — "패딩 보관법"이 음식으로 가지 않게
  [(p) => /세탁|빨래|청소|곰팡이|결로|냄새|벌레|초파리|진드기|이불|커튼|패딩|니트|옷|신발|수납|정리|보일러|난방|외풍|문풍지|동파|가습기|제습|배수구|하수구|세탁기|냉장고 정리|창문|욕실|화장실|현관/.test(p.text), '인테리어·DIY'],
  [(p) => /제철|손질|레시피|만들기|담그|조림|볶|굽|삶|찌는|찜|김장|반찬|도시락|김치|묵|청 만들|보관법|보관|요리|간식|식단|메뉴|고르는 ?법/.test(p.text), '요리·레시피'],
];

export function guessTopic({ title = '', mainKeyword = '', category = '' } = {}) {
  const p = { text: `${title} ${mainKeyword}`, category };
  for (const [test, topic] of RULES) if (test(p)) return topic;
  return '인테리어·DIY';
}

/** 프런트매터 topic 이 있으면 그것(목록에 없는 이름이면 null 로 알린다), 없으면 규칙으로 */
export function topicFor(post) {
  const t = (post.topic || '').trim();
  if (t) return NAVER_TOPICS.includes(t) ? t : null;
  return guessTopic(post);
}
