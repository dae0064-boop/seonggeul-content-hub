/**
 * GOMS 광고심의 수정요구(반려)를 부르는 단정 표현 — 실제 반려 사례에서 모은다 (정본: content/threads/insurance/rules.md "심의 반려 사례").
 * 스레드 보험글(insurance-set.mjs)·인스타 카드뉴스(render-cards.mjs)가 같이 쓴다.
 *
 * 2026-11-03 스레드 39편 수정요구 (상법 651·655조 글):
 *  ① "안 날부터 1개월, 계약한 날부터 3년 안에만 돼" — 해지권·제척기간은 고의·중과실, 보험 종류, 약관, 판례에 따라 다툼이 생길 수 있어 확정적 단정 금지
 *  ② "상관없다는 게 증명되면 보험금은 줘야 해" — 원칙은 맞아도 실제 지급은 약관·사실관계·입증책임에 따라 달라 '반드시 지급'처럼 읽히면 안 됨
 *  → "사안에 따라 제한이 있을 수 있어", "지급이 인정될 여지도 있어. 다만 계약 유지/해지 여부는 별도로 판단될 수 있어" 로 쓴다.
 */
export const RISKY = [
  { re: /(안에만|까지만)\s*(돼|된다|가능|할 수 있)/, why: '기간을 "~안에만 돼"로 못 박음 (해지권·제척기간 단정) → "사안에 따라 제한이 있을 수 있어"' },
  { re: /(보험금[^.\n]{0,12}줘야|안에\s*줘야|해\s*줘야\s*(해|돼|한다|해요|합니다)|지급해야|돌려줘야|반드시\s*지급|무조건\s*지급|지급\s*의무가\s*있)/, why: '보험사가 "줘야/지급해야" 한다고 단정 → "지급이 인정될 여지도 있어"' },
  { re: /(해지할\s*수\s*없|해지\s*못\s*(해|함|한다|합니다)|해지가\s*안\s*(돼|됩))/, why: '"해지 못 한다"고 단정 → "해지가 제한될 수 있어"' },
  { re: /증명되면/, why: '"증명되면 ~된다" 단정 (입증책임·사실관계에 따라 다름) → "판단되는 경우에는 ~여지도 있어"' },
  { re: /(\d+\s*(일|개월|년))\s*안에\s*(계약을\s*)?해지할\s*수\s*있/, why: '보험사 해지 기간을 숫자로 못 박음 → "해지할 수 있는 기간은 사안에 따라 제한이 있을 수 있어"' },
];

/** 글에서 걸리는 표현들 [{ text, why }]. 따옴표 속 남의 말(질문)도 그대로 본다 — 심의는 글 전체를 본다. */
export function riskyIn(text) {
  const hits = [];
  for (const { re, why } of RISKY) {
    const m = String(text).match(re);
    if (m) hits.push({ text: m[0], why });
  }
  return hits;
}
